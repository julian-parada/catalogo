-- =====================================================================
-- 008 · Historial de ventas
--   Cada vez que la tienda toca "Vendido" en el panel se guarda una fila aquí:
--   qué producto, qué opción (talla/color), a qué precio y cuándo.
--   Se guardan nombre, categoría y foto tal como estaban, para que el historial
--   siga completo aunque después se edite o se borre el producto.
--   Solo el admin de cada tienda ve y cambia sus ventas.
--   Se puede correr más de una vez sin problema.
-- =====================================================================

begin;

create table if not exists public.ventas (
  id          bigint generated by default as identity primary key,
  tienda_id   uuid not null references public.clientes(id) on delete cascade,
  prenda_id   bigint references public.prendas(id) on delete set null,
  talla_id    bigint references public.tallas(id) on delete set null,
  producto    text not null,
  opcion      text,
  categoria   text,
  imagen      text,
  precio      numeric not null,
  cantidad    integer not null default 1,
  vendido_en  timestamptz not null default now(),
  constraint ventas_producto_largo  check (char_length(producto) between 1 and 200),
  constraint ventas_opcion_largo    check (opcion is null or char_length(opcion) <= 80),
  constraint ventas_categoria_largo check (categoria is null or char_length(categoria) <= 80),
  constraint ventas_imagen_largo    check (imagen is null or char_length(imagen) <= 1000),
  constraint ventas_precio_valido   check (precio >= 0 and precio <= 1000000000),
  constraint ventas_cantidad_valida check (cantidad between 1 and 999)
);

-- Consultas del historial: por tienda y fecha
create index if not exists ventas_tienda_fecha_idx on public.ventas (tienda_id, vendido_en desc);
create index if not exists ventas_prenda_idx on public.ventas (prenda_id);

alter table public.ventas enable row level security;

drop policy if exists "admin ventas" on public.ventas;
create policy "admin ventas" on public.ventas for all to authenticated
  using (tienda_id = (select public.mi_tienda()))
  with check (tienda_id = (select public.mi_tienda()));

revoke all on public.ventas from anon;
grant select, insert, update, delete on public.ventas to authenticated;

commit;
